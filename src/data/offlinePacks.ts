// World destination resolver that supports ANY country or city
export function resolveWorldwideDestination(inputQuery: string): DestinationInfo {
  if (!inputQuery || !inputQuery.trim()) {
    return POPULAR_DESTINATIONS[0];
  }

  const clean = inputQuery.trim().toLowerCase();

  // 1. Direct match on ID, name, or country
  const directMatch = POPULAR_DESTINATIONS.find(
    (d) =>
      d.id.toLowerCase() === clean ||
      d.name.toLowerCase() === clean ||
      d.country.toLowerCase() === clean ||
      clean.includes(d.name.toLowerCase()) ||
      clean.includes(d.country.toLowerCase())
  );
  if (directMatch) return directMatch;

  // 2. City Alias lookup
  for (const [city, destId] of Object.entries(CITY_ALIASES)) {
    if (clean.includes(city)) {
      const match = POPULAR_DESTINATIONS.find((d) => d.id === destId);
      if (match) return match;
    }
  }

  // 3. Dynamic destination for any custom place worldwide (e.g. Iceland, Norway, Peru, etc.)
  const formattedName = inputQuery.trim().replace(/\b\w/g, (c) => c.toUpperCase());
  const customId = clean.replace(/[^a-z0-9]/g, '-').slice(0, 20);

  return {
    id: customId || 'worldwide-custom',
    name: formattedName,
    country: formattedName,
    flag: '🌍',
    currency: 'Local Currency',
    currencySymbol: '$',
    officialLanguage: 'Local Language',
    languageCode: 'en',
    speechVoiceLang: 'en-US',
    emergencyNumbers: {
      police: '112 / 911',
      ambulance: '112 / 911',
      fire: '112 / 911',
      touristHotline: '112 (Universal Emergency)',
    },
    capital: formattedName,
    region: 'Worldwide',
    trustedTaxiBrands: ['Official Metered City Taxis', 'Uber / Local Ride-hail App'],
    commonScams: [
      'Unmetered airport taxis overcharging arrivals; agree on rate or verify meter before moving',
      'Unofficial currency exchange booths charging hidden fees',
    ],
    tapWaterDrinkable: false,
    tippingCulture: 'Check local restaurant customs; 10% is customary in many international destinations.',
  };
}

